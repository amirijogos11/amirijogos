/* =====================================================
   IDIOMA ATUAL
===================================================== */

let amiriLanguage =
localStorage.getItem(
  "amirijogosLanguage"
) || "pt";


function t(key){

  return (
    AMIRI_TRANSLATIONS[
      amiriLanguage
    ]?.[key]
    ||
    AMIRI_TRANSLATIONS.pt[key]
    ||
    key
  );

}


/* =====================================================
   ALTERAR IDIOMA
===================================================== */

function setAmiriLanguage(language){

  if(
    !AMIRI_TRANSLATIONS[language]
  ){
    return;
  }


  amiriLanguage =
  language;


  localStorage.setItem(
    "amirijogosLanguage",
    language
  );


  document.documentElement.lang =
  language === "pt"
    ? "pt-PT"
    : language;


  translatePage();


  document.dispatchEvent(
    new CustomEvent(
      "amirilanguagechange",
      {
        detail:{
          language
        }
      }
    )
  );

}


/* =====================================================
   TRADUZIR ELEMENTOS
===================================================== */

function translatePage(){

  document
  .querySelectorAll(
    "[data-i18n]"
  )
  .forEach(
    element=>{

      const key =
      element.dataset.i18n;


      element.textContent =
      t(key);

    }
  );


  document
  .querySelectorAll(
    "[data-i18n-placeholder]"
  )
  .forEach(
    element=>{

      const key =
      element.dataset.i18nPlaceholder;


      element.placeholder =
      t(key);

    }
  );


  document
  .querySelectorAll(
    "[data-language]"
  )
  .forEach(
    button=>{

      button.classList.toggle(
        "selected-language",
        button.dataset.language ===
        amiriLanguage
      );

    }
  );

}


/* =====================================================
   START
===================================================== */

document.addEventListener(
  "DOMContentLoaded",
  ()=>{

    translatePage();

  }
);
