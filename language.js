/* =====================================================
   CURRENT LANGUAGE
===================================================== */

let amiriLanguage =
localStorage.getItem(
  "amirijogosLanguage"
) || "pt";


/* =====================================================
   TRANSLATION FUNCTION
===================================================== */

function t(key){

  return (
    AMIRI_TRANSLATIONS[
      amiriLanguage
    ]?.[key]
    ??
    AMIRI_TRANSLATIONS.pt[
      key
    ]
    ??
    key
  );

}


/* =====================================================
   TRANSLATE PAGE
===================================================== */

function translatePage(){

  document
  .querySelectorAll(
    "[data-i18n]"
  )
  .forEach(
    element=>{

      const key =
      element.dataset.i18n;

      element.textContent =
      t(key);

    }
  );


  document
  .querySelectorAll(
    "[data-i18n-placeholder]"
  )
  .forEach(
    element=>{

      element.placeholder =
      t(
        element.dataset
        .i18nPlaceholder
      );

    }
  );


  document
  .querySelectorAll(
    "[data-language]"
  )
  .forEach(
    button=>{

      button.classList.toggle(
        "selected-language",
        button.dataset.language ===
        amiriLanguage
      );

    }
  );

}


/* =====================================================
   SET LANGUAGE
===================================================== */

function setAmiriLanguage(
  language
){

  if(
    !AMIRI_TRANSLATIONS[
      language
    ]
  ){
    return;
  }

  amiriLanguage =
  language;

  localStorage.setItem(
    "amirijogosLanguage",
    language
  );

  document.documentElement.lang =
  language==="pt"
  ? "pt-PT"
  : language;

  translatePage();

  document.dispatchEvent(
    new CustomEvent(
      "amirilanguagechange",
      {
        detail:{
          language
        }
      }
    )
  );

}


/* =====================================================
   START
===================================================== */

if(
  document.readyState===
  "loading"
){

  document.addEventListener(
    "DOMContentLoaded",
    translatePage
  );

}else{

  translatePage();

}
